#!/usr/bin/env python3
"""Compile the reviewed logical story IDs into the runtime bitmap; --check verifies it."""
import csv
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
bitmap = bytearray(151)
seen = set()
with (root / "docs/story-sync-policy.tsv").open() as source:
    for entry in csv.DictReader(source, delimiter="\t"):
        flag = int(entry["id"])
        if not 0 <= flag < 1202 or flag in seen:
            raise ValueError(f"Invalid or repeated story flag {flag}")
        seen.add(flag)
        bitmap[flag // 8] |= 1 << (flag % 8)
text = "// Generated by scripts/update-story-policy.py from docs/story-sync-policy.tsv.\n"
text += "// Logical IDs from the CC0 ss flag map. Runtime also requires a one-bit HD definition.\n"
text += "static const uint8_t story_policy[151] = {\n"
for offset in range(0, len(bitmap), 16):
    text += "    " + ", ".join(f"0x{value:02x}" for value in bitmap[offset:offset + 16]) + ",\n"
text += "};\n"
target = root / "client/src/sst_story_policy.inc"
if "--check" in sys.argv:
    if target.read_text() != text:
        raise SystemExit("Story policy bitmap is stale; run scripts/update-story-policy.py")
else:
    target.write_text(text)
print(f"Story policy: {len(seen)} reviewed IDs; runtime definition checks still apply")
