#!/usr/bin/env python3
"""Generate C/relay lookup data from reviewed, asset-free vanilla reward identities."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = []
    for line in (ROOT / 'docs/reward-catalogue.tsv').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        index, item, stages = line.split('\t')
        index, item = int(index), int(item)
        if not 0 <= index < 4160 or not 0 < item < 511 or not stages:
            raise ValueError(f'Invalid reward: {line}')
        rows.append((index, item))
    if rows != sorted(rows) or len({index for index, _ in rows}) != len(rows):
        raise ValueError('Reward identities must be unique and sorted')
    outputs = {
        'client/src/sst_reward_catalogue.inc':
            '// Generated by scripts/update-reward-catalogue.py; review docs/reward-catalogue.tsv.\n'
            'static const uint16_t saved_rewards[SST_CHESTS] = {\n'
            + ''.join(f'    [{index}] = {item},\n' for index, item in rows) + '};\n',
        'server/reward-catalogue.json': json.dumps(rows, separators=(',', ':')) + '\n',
    }
    for name, content in outputs.items():
        path = ROOT / name
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'{name} is stale; run scripts/update-reward-catalogue.py')
        else:
            path.write_text(content)
    print(f'Reward catalogue: {len(rows)} reviewed permanent collection receipts')


if __name__ == '__main__':
    main()
